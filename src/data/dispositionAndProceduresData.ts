function classifyDispositionGroup(closeType: string): string {
  if (closeType.includes('Tele')) return 'การแพทย์ทางไกล (Telemedicine)';
  if (closeType.includes('EMS') || closeType.includes('ไปรษณีย์') || closeType.includes('ญาติรับยาแทน')) {
    return 'บริการส่งยา/รับยาแทน (ลดแออัด)';
  }
  if (closeType.includes('ER-')) return 'ส่งต่อห้องฉุกเฉิน (ER)';
  if (closeType.includes('Consult') || closeType.includes('ปรึกษา')) return 'ปรึกษาแพทย์เฉพาะทาง (Consult)';
  if (closeType.includes('ตรวจต่อ') || closeType.includes('ส่งต่อ') || closeType.includes('Admit') || closeType.includes('Refer') || closeType.includes('Ward') || closeType.includes('ส่งนัด')) {
    return 'ส่งต่อรักษา/ตรวจต่อ/Admit';
  }
  if (closeType.includes('ฉีดยา') || closeType.includes('ทำแผล') || closeType.includes('ตัดไหม') || closeType.includes('ทำหัตถการ')) {
    return 'หัตถการ/ฉีดยา/ทำแผลแล้วกลับบ้าน';
  }
  if (closeType.includes('ไม่มี CloseVisit') || closeType.includes('ยังไม่สิ้นสุด') || closeType.includes('รอผล') || closeType.includes('ไม่ยอมรับ')) {
    return 'รอดำเนินการ/ไม่ระบุการจำหน่าย';
  }
  return 'ตรวจเสร็จ/รับยากลับบ้านปกติ';
}

function classifyProcedureCategory(code: string, name: string): string {
  if (code.startsWith('1B') || code.startsWith('1J') || name.includes('SpecialPP') || name.includes('Community Service')) {
    return 'คัดกรองและส่งเสริมสุขภาพ (SpecialPP / ชุมชน)';
  }
  if (name.includes('คำแนะนำ') || name.includes('สุขศึกษา') || name.includes('Self care') || name.includes('Mental Support') || name.includes('Consult Nutrition')) {
    return 'ให้คำปรึกษาและสุขศึกษา';
  }
  if (name.includes('Dressing') || name.includes('ทำแผล') || name.includes('ตัดไหม') || name.includes('Suture') || name.includes('Stapple') || name.includes('I&D') || name.includes('Cath') || name.includes('Drain') || name.includes('Aspirate')) {
    return 'หัตถการทำแผลและศัลยกรรมเล็ก';
  }
  if (name.includes('Injection') || name.includes('ฉีดยา') || name.includes('IV fluid') || name.includes('Neubulizer') || name.includes('Oxygen') || name.includes('I.V.fluid')) {
    return 'ฉีดยา วัคซีน ให้น้ำเกลือ และพ่นยา';
  }
  if (name.includes('X-ray') || name.includes('EKG') || name.includes('CT') || name.includes('เจาะเลือด') || name.includes('Eyesight') || name.includes('Rhinoscopy') || name.includes('IDL') || name.includes('Eye washing')) {
    return 'ตรวจพิเศษทางห้องปฏิบัติการ/รังสี/EKG';
  }
  return 'บริการตรวจพื้นฐาน/ทะเบียน/อื่นๆ';
}

